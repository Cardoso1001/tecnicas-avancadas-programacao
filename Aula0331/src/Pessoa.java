

public class Pessoa {
    private String nome;
    private String cpf;
    private String tel;
    
    public void setNome(String n){
        this.nome = n;
    }
    public String getNome() {
        return this.nome;
    }
    public void setCPF(String c){
        this.cpf = c;
    }
    public String getCPF() {
        return this.cpf;
    }
    public void setTelefone(String t){
        this.tel = t;
    }
    public String getTelefone() {
        return this.tel;
    }
}
